# ANC modes
ANC_OFF          = 0x00
ANC_TRANSPARENCY = 0x01
ANC_LIGHT        = 0x02
ANC_MAX          = 0x03

# EQ presets
EQ_BALANCED      = 0x00
EQ_BASS_BOOST    = 0x01
EQ_TREBLE_BOOST  = 0x02
EQ_PODCAST       = 0x03
EQ_GAMING        = 0x04

# Gesture actions

# Packet framing
MAGIC = bytes([0xAA, 0xBB])
MAX_PAYLOAD = 512

# Commands (to-device)
CMD_GET_BATTERY   = 0x05
CMD_SET_ANC       = 0x06
CMD_GET_ANC       = 0x07
CMD_SET_EQ        = 0x08
CMD_GET_EQ        = 0x09
CMD_SET_GESTURE   = 0x0A
